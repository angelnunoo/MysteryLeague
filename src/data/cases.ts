export function caseById(id: string): MysteryCase | undefined {
  return CASES.find((mystery) => mystery.id === id) ?? eventCaseById(id) ?? generatedById(id)
}

export function weeklyCases(date = new Date()): MysteryCase[] {
  const week = isoWeek(date)
  const first = week % CASES.length
  let second = (week + 2) % CASES.length
  if (second === first) second = (first + 1) % CASES.length
  return [CASES[first], CASES[second]]
}

